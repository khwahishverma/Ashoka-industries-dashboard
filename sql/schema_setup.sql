-- Run in the Supabase SQL Editor. Safe to rerun; this does not drop data.
-- RLS is enabled with no anon/authenticated policies: the Streamlit server
-- accesses these tables using a server-side Supabase secret/service-role key.

CREATE TABLE IF NOT EXISTS public.sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date DATE NOT NULL,
    bill_no VARCHAR(50),
    customer_name VARCHAR(150),
    quantity NUMERIC(10, 2),
    amount NUMERIC(15, 2),
    transaction_type VARCHAR(30),
    period VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS public.purchases (
    purchase_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_date DATE NOT NULL,
    bill_no VARCHAR(50),
    item_name VARCHAR(100),
    hsn_code VARCHAR(30),
    gst_amount NUMERIC(15, 2),
    purchase_amount NUMERIC(15, 2),
    period VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS public.consumables (
    consumable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumable_date DATE NOT NULL,
    bill_no VARCHAR(50),
    item_name VARCHAR(150),
    quantity NUMERIC(10, 2),
    amount NUMERIC(15, 2),
    period VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS public.sales_adjustments (
    adjustment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_date DATE NOT NULL,
    reference VARCHAR(100),
    description VARCHAR(200),
    amount NUMERIC(15, 2),
    adjustment_type VARCHAR(50)
);

ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.purchases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consumables ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales_adjustments ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS sales_sale_date_idx ON public.sales (sale_date);
CREATE INDEX IF NOT EXISTS purchases_purchase_date_idx ON public.purchases (purchase_date);
CREATE INDEX IF NOT EXISTS consumables_consumable_date_idx ON public.consumables (consumable_date);
CREATE INDEX IF NOT EXISTS sales_adjustments_adjustment_date_idx
    ON public.sales_adjustments (adjustment_date);
